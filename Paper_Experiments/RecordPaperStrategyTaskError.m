function Study=RecordPaperStrategyTaskError(Study,ni,run,caseIndex,name,seed,failure)
%RECORDPAPERSTRATEGYTASKERROR Preserve failure history without inventing TC.
record=struct('N',Study.Config.NList(ni),'Strategy',name,'Run',run,'Seed',seed, ...
    'Attempt',Study.AttemptCounts(ni,run,caseIndex),'Identifier',failure.Identifier, ...
    'Message',failure.Message,'Report',failure.Report,'OccurredAt',failure.At, ...
    'IsGlobalBlocker',failure.IsGlobalBlocker,'Resolved',false,'ResolvedAt','', ...
    'ElapsedSeconds',failure.ElapsedSeconds);
Study.Failures{ni,run,caseIndex}=record;
if isempty(Study.ErrorRecords), Study.ErrorRecords=record;
else, Study.ErrorRecords(end+1)=record; end
end
