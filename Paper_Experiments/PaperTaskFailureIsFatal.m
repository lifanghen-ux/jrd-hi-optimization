function fatal=PaperTaskFailureIsFatal(exception)
%PAPERTASKFAILUREISFATAL Model/input/checkpoint integrity cannot be skipped.
% Search failures belonging to one independent task may be recorded and the
% queue continued. Invalid data or mismatched costs must stop the queue.
id=exception.identifier;
fatalIds={'JRD:CostMismatch','JRD:InvalidData','JRD:InvalidBounds', ...
    'JRD:InvalidPartition','JRD:InvalidGroup','JRD:InvalidCost', ...
    'JRD:EvolutionOptions','JRD:InitialPartition','JRD:GridRange', ...
    'JRD:StaleCheckpoint','JRD:StaleRawRecord','JRD:InvalidRawSchema', ...
    'JRD:FixedInstanceDesign','JRD:ResultWrite','JRD:Baseline', ...
    'JRD:FrequencyBounds','JRD:FixedFrequency', ...
    'JRD:CheckpointSchema','JRD:TeacherImplementation', ...
    'MATLAB:UndefinedFunction','MATLAB:scriptNotAFunction', ...
    'MATLAB:nonExistentField','MATLAB:structRefFromNonStruct', ...
    'MATLAB:nomem','MATLAB:outOfMemory'};
fatal=ismember(id,fatalIds)||startsWith(id,'JRD:Model')|| ...
    startsWith(id,'MATLAB:expected')||startsWith(id,'MATLAB:InputParser')|| ...
    startsWith(id,'MATLAB:save:')||startsWith(id,'MATLAB:FileIO');
end
